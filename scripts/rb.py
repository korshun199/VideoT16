def hex_в_rgb(цвет):
    """Преобразует '#ffffff' в (255, 255, 255)."""

    цвет = цвет.strip().lstrip("#")

    if len(цвет) != 6:
        raise ValueError(
            f"Неверный цвет: #{цвет}. Нужен формат #RRGGBB"
        )

    return tuple(
        int(цвет[i:i + 2], 16)
        for i in (0, 2, 4)
    )


def применить_яркость_osd(цвет):
    """Применяет общую яркость к цветам OSD."""

    return tuple(
        max(0, min(255, int(c * ЯРКОСТЬ_OSD)))
        for c in цвет
    )


def вывести(
    окно,
    текст,
    x,
    y,
    размер=32,
    цвет="#ffffff",
    жирный=True
):
    """
    Универсальный вывод текста на экран.

    Пример:
        вывести(
            окно,
            "ЦЕЛЬ",
            100,
            100,
            размер=50,
            цвет="#ff0000"
        )
    """

    rgb = применить_яркость_osd(
        hex_в_rgb(цвет)
    )

    шрифт = pygame.font.SysFont(
        "DejaVu Sans Mono",
        размер,
        bold=жирный
    )

    поверхность = шрифт.render(
        str(текст),
        True,
        rgb
    )

    окно.blit(
        поверхность,
        (x, y)
    )


