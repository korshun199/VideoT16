class СвежаяКамера:
    """Читает USB-камеру в фоне и хранит только последний кадр."""

    def __init__(self, камера):
        self.камера = камера
        self.кадр = None
        self.блокировка = threading.Lock()
        self.работает = True
        self.поток = threading.Thread(target=self._читать, daemon=True)
        self.поток.start()

    def _читать(self):
        """Постоянно заменяет старый кадр самым свежим."""
        while self.работает:
            ok, кадр = self.камера.read()
            if ok and кадр is not None:
                with self.блокировка:
                    self.кадр = кадр

    def read(self):
        """Возвращает последний доступный кадр без очереди старых кадров."""
        with self.блокировка:
            if self.кадр is None:
                return False, None
            return True, self.кадр.copy()

    def release(self):
        """Останавливает поток и освобождает USB-камеру."""
        self.работает = False
        self.поток.join(timeout=1.0)
        self.камера.release()

def открыть_камеру():
    """Открываем USB-камеру. Если выбранная не открылась, пробуем 0..5."""

    кандидаты = [НОМЕР_КАМЕРЫ] + [
        n for n in range(6)
        if n != НОМЕР_КАМЕРЫ
    ]

    for номер in кандидаты:
        камера = cv2.VideoCapture(
            номер,
            cv2.CAP_V4L2
        )

        if not камера.isOpened():
            камера.release()
            continue

        камера.set(
            cv2.CAP_PROP_FRAME_WIDTH,
            ШИРИНА_КАМЕРЫ
        )

        камера.set(
            cv2.CAP_PROP_FRAME_HEIGHT,
            ВЫСОТА_КАМЕРЫ
        )

        камера.set(
            cv2.CAP_PROP_FOURCC,
            cv2.VideoWriter_fourcc(*"MJPG")
        )

        камера.set(
            cv2.CAP_PROP_BUFFERSIZE,
            1
        )

        камера.set(
            cv2.CAP_PROP_FPS,
            FPS_КАМЕРЫ
        )

        # Минимальный буфер уменьшает задержку, если драйвер это поддерживает.
        камера.set(
            cv2.CAP_PROP_BUFFERSIZE,
            1
        )

        ширина = int(
            камера.get(
                cv2.CAP_PROP_FRAME_WIDTH
            )
        )

        высота = int(
            камера.get(
                cv2.CAP_PROP_FRAME_HEIGHT
            )
        )

        fps = камера.get(
            cv2.CAP_PROP_FPS
        )

        print(
            f"Камера открыта: /dev/video{номер}, "
            f"{ширина}x{высота}, {fps:.1f} FPS"
        )

        return СвежаяКамера(камера)

    raise RuntimeError(
        "USB-камера не найдена. "
        "Проверь: v4l2-ctl --list-devices"
    )


def изменить_яркость_кадра(кадр):
    """Программная регулировка яркости видео."""

    if ЯРКОСТЬ_ВИДЕО == 1.0:
        return кадр

    return cv2.convertScaleAbs(
        кадр,
        alpha=ЯРКОСТЬ_ВИДЕО,
        beta=0
    )


def подготовить_видео(кадр, ширина_экрана, высота_экрана):
    """Масштабируем кадр под HDMI с сохранением пропорций."""

    if ЗЕРКАЛО_ВИДЕО:
        кадр = cv2.flip(
            кадр,
            1
        )

    кадр = изменить_яркость_кадра(
        кадр
    )

    h, w = кадр.shape[:2]

    if w <= 0 or h <= 0:
        return None, (0, 0)

    масштаб_x = ширина_экрана / w
    масштаб_y = высота_экрана / h

    if РЕЖИМ_ВИДЕО == "fit":
        масштаб = min(
            масштаб_x,
            масштаб_y
        )
    else:
        масштаб = max(
            масштаб_x,
            масштаб_y
        )

    новая_ширина = max(
        1,
        int(w * масштаб)
    )

    новая_высота = max(
        1,
        int(h * масштаб)
    )

    кадр = cv2.resize(
        кадр,
        (
            новая_ширина,
            новая_высота
        ),
        interpolation=cv2.INTER_LINEAR
    )

    if РЕЖИМ_ВИДЕО == "cover":

        x0 = max(
            0,
            (
                новая_ширина
                - ширина_экрана
            ) // 2
        )

        y0 = max(
            0,
            (
                новая_высота
                - высота_экрана
            ) // 2
        )

        кадр = кадр[
            y0:y0 + высота_экрана,
            x0:x0 + ширина_экрана
        ]

        позиция = (
            0,
            0
        )

    else:

        позиция = (
            (
                ширина_экрана
                - новая_ширина
            ) // 2,
            (
                высота_экрана
                - новая_высота
            ) // 2
        )

    # OpenCV BGR -> RGB.
    кадр = cv2.cvtColor(
        кадр,
        cv2.COLOR_BGR2RGB
    )

    # Pygame ожидает оси ширина x высота.
    поверхность = pygame.surfarray.make_surface(
        кадр.swapaxes(
            0,
            1
        )
    )

    return поверхность, позиция


