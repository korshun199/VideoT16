НАШ_OSD_X = 20
НАШ_OSD_Y = 6

# Символ нашей тестовой метки. Знак '+' есть в стандартном шрифте MAX7456.
НАШ_OSD_СИМВОЛ = ord("+")

# Атрибуты строки DisplayPort: стандартный белый символ без инверсии.
НАШ_OSD_АТРИБУТЫ = 0

# Размер сетки Betaflight HD OSD.
ШИРИНА_OSD = 40
ВЫСОТА_OSD = 12


