def очистить_рабочий():
    """Очищаем новый формируемый OSD-кадр."""

    global рабочий_экран

    рабочий_экран = [
        [" " for _ in range(ШИРИНА_OSD)]
        for _ in range(ВЫСОТА_OSD)
    ]


def записать_osd(row, col, данные):
    """Записываем строку DisplayPort в рабочий OSD-кадр."""

    if row >= ВЫСОТА_OSD:
        return

    for i, b in enumerate(данные):

        x = col + i

        if x >= ШИРИНА_OSD:
            break

        if 32 <= b <= 126:
            рабочий_экран[row][x] = chr(b)

        else:
            # Позже заменим на настоящие глифы шрифта Betaflight.
            рабочий_экран[row][x] = "◆"


def показать_новый_кадр():
    """Делаем полностью собранный OSD-кадр видимым."""

    global видимый_экран
    global кадров_osd

    кадров_osd += 1

    видимый_экран = [
        row.copy()
        for row in рабочий_экран
    ]


def обработать_displayport(payload):
    """Обрабатываем MSP_DISPLAYPORT."""

    if not payload:
        return

    команда = payload[0]

    # HEARTBEAT
    if команда == 0:
        return

    # RELEASE
    if команда == 1:
        return

    # CLEAR SCREEN
    if команда == 2:
        очистить_рабочий()
        return

    # WRITE STRING
    if команда == 3 and len(payload) >= 4:

        row = payload[1]
        col = payload[2]

        # payload[3] содержит атрибуты шрифта.
        данные = payload[4:]

        записать_osd(
            row,
            col,
            данные
        )

        return

    # DRAW SCREEN
    if команда == 4:

        показать_новый_кадр()
        return


def собрать_msp_displayport(payload):
    """Собираем MSP_DISPLAYPORT-пакет для передачи в OSD."""

    команда = 182
    длина = len(payload)
    контрольная_сумма = длина ^ команда

    for байт in payload:
        контрольная_сумма ^= байт

    return bytes(
        b"$M>"
        + bytes([длина, команда])
        + bytes(payload)
        + bytes([контрольная_сумма])
    )


def отправить_нашу_метку(порт):
    """Добавляем тестовый прицел в выходной MSP DisplayPort-поток."""

    if not ПЕРЕДАВАТЬ_НАШ_OSD:
        return 0

    x = max(0, min(ШИРИНА_OSD - 1, НАШ_OSD_X))
    y = max(0, min(ВЫСОТА_OSD - 1, НАШ_OSD_Y))

    # Команда 3 — WRITE STRING: [команда, строка, столбец, атрибут, символ].
    запись = собрать_msp_displayport(
        bytes([3, y, x, НАШ_OSD_АТРИБУТЫ, НАШ_OSD_СИМВОЛ])
    )

    # Команда 4 — DRAW SCREEN: показать добавленную строку.
    отрисовка = собрать_msp_displayport(bytes([4]))

    порт.write(запись)
    порт.write(отрисовка)

    return 2


