def открыть_monitor():
    """Открываем полноэкранное окно на выбранном мониторе."""

    pygame.init()

    количество = pygame.display.get_num_displays()

    print(
        f"Мониторов найдено: {количество}"
    )

    monitor = НОМЕР_МОНИТОРА

    if monitor >= количество:

        print(
            f"Монитор №{monitor} отсутствует, "
            f"использую основной."
        )

        monitor = 0

    окно = pygame.display.set_mode(
        (0, 0),
        pygame.FULLSCREEN,
        display=monitor
    )

    pygame.mouse.set_visible(
        False
    )

    return окно


def нарисовать_osd(окно):
    """Рисуем Betaflight OSD поверх видео."""

    ширина = окно.get_width()
    высота = окно.get_height()

    шаг_x = (
        ширина
        / ШИРИНА_OSD
        * МАСШТАБ_X
    )

    шаг_y = (
        высота
        / ВЫСОТА_OSD
        * МАСШТАБ_Y
    )

    for row in range(
        ВЫСОТА_OSD
    ):

        for col in range(
            ШИРИНА_OSD
        ):

            символ = видимый_экран[
                row
            ][
                col
            ]

            if символ == " ":
                continue

            x = int(
                col * шаг_x
                + СМЕЩЕНИЕ_X
            )

            y = int(
                row * шаг_y
                + СМЕЩЕНИЕ_Y
            )

            вывести(
                окно,
                символ,
                x,
                y,
                размер=РАЗМЕР_ШРИФТА,
                цвет=ЦВЕТ_OSD,
                жирный=ЖИРНЫЙ_ШРИФТ
            )


def нарисовать_прицел(окно):
    """Рисуем центральный прицел поверх видео."""

    цвет = применить_яркость_osd(
        hex_в_rgb(
            ЦВЕТ_ПРИЦЕЛА
        )
    )

    cx = окно.get_width() // 2
    cy = окно.get_height() // 2

    pygame.draw.line(
        окно,
        цвет,
        (
            cx - РАЗМЕР_ПРИЦЕЛА,
            cy
        ),
        (
            cx + РАЗМЕР_ПРИЦЕЛА,
            cy
        ),
        ТОЛЩИНА_ПРИЦЕЛА
    )

    pygame.draw.line(
        окно,
        цвет,
        (
            cx,
            cy - РАЗМЕР_ПРИЦЕЛА
        ),
        (
            cx,
            cy + РАЗМЕР_ПРИЦЕЛА
        ),
        ТОЛЩИНА_ПРИЦЕЛА
    )


def нарисовать_статус(окно):
    """Служебная строка для лабораторного режима."""

    if not ПОКАЗЫВАТЬ_СТАТУС:
        return

    прошло_osd = (
        time.time()
        - последний_пакет
    )

    прошло_видео = (
        time.time()
        - последний_кадр_камеры
    )

    статус = (
        f"VIDEO {кадров_видео}   "
        f"OSD пакетов {пакетов}   "
        f"OUT {отправлено_пакетов}   "
        f"OSD кадров {кадров_osd}   "
        f"UART {прошло_osd:.1f} c   "
        f"CAM {прошло_видео:.1f} c"
    )

    вывести(
        окно,
        статус,
        20,
        15,
        размер=18,
        цвет=ЦВЕТ_СТАТУСА,
        жирный=False
    )


def рисовать(
    окно,
    поверхность_видео=None,
    позиция_видео=(0, 0)
):
    """Рисуем видео, затем поверх него OSD."""

    # Если кадра камеры ещё нет, показываем фон.
    окно.fill(
        hex_в_rgb(
            ЦВЕТ_ФОНА
        )
    )

    if поверхность_видео is not None:

        окно.blit(
            поверхность_видео,
            позиция_видео
        )

    # Штатный OSD можно отключить, оставив только нашу графику.
    if ПОКАЗЫВАТЬ_ШТАТНЫЙ_OSD:
        нарисовать_osd(окно)

    нарисовать_прицел(
        окно
    )

    нарисовать_статус(
        окно
    )

    pygame.display.flip()


