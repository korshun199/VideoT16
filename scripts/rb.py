ЦВЕТ_СТАТУСА = "#ffffff"
ЦВЕТ_ФОНА = "#000000"

# Общая яркость OSD от 0.0 до 1.0
ЯРКОСТЬ_OSD = 0.95

ЖИРНЫЙ_ШРИФТ = True

РАЗМЕР_ПРИЦЕЛА = 35
ТОЛЩИНА_ПРИЦЕЛА = 5

