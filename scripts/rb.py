# ============================================================

def main():

    global пакетов
    global последний_пакет
    global кадров_видео
    global последний_кадр_камеры
    global отправлено_пакетов
    global отправлено_наших_пакетов

    ser = None
    ser_out = None

    try:
        ser = serial.Serial(
            ПОРТ,
            СКОРОСТЬ,
            timeout=0
        )
    except serial.SerialException:
        print(f"OSD вход не подключён: {ПОРТ}; работаю локально")

    try:
        ser_out = serial.Serial(
            ПОРТ_ВЫХОДА,
            СКОРОСТЬ,
            timeout=0,
            write_timeout=1
        )
    except serial.SerialException:
        print(f"OSD выход не подключён: {ПОРТ_ВЫХОДА}; работаю локально")

    if ser is not None and ser_out is not None:
        print(
            f"OSD вход: {ПОРТ}; OSD выход: {ПОРТ_ВЫХОДА}; "
            "прозрачная передача включена"
        )

    камера = открыть_камеру()

    окно = открыть_monitor()

    буфер = bytearray()

    часы = pygame.time.Clock()

    работает = True

    поверхность_видео = None
    позиция_видео = (
        0,
        0
    )

    try:

        while работает:

            # ------------------------------------------------
            # Клавиатура
            # ------------------------------------------------

            for event in pygame.event.get():

                if event.type == pygame.QUIT:
                    работает = False

                elif event.type == pygame.KEYDOWN:

                    if event.key in (
                        pygame.K_ESCAPE,
                        pygame.K_q
                    ):
                        работает = False

            # ------------------------------------------------
            # КАМЕРА
            # ------------------------------------------------

            ok, кадр = камера.read()

            if ok:

                кадров_видео += 1
                последний_кадр_камеры = time.time()

                поверхность_видео, позиция_видео = подготовить_видео(
                    кадр,
                    окно.get_width(),
                    окно.get_height()
                )

            # ------------------------------------------------
            # UART / MSP DISPLAYPORT
            # ------------------------------------------------

            данные = ser.read(4096) if ser is not None else b""

            if данные:

                последний_пакет = time.time()

                буфер.extend(
                    данные
                )

            while True:

                начало = буфер.find(
                    b"$M>"
                )

                if начало < 0:

                    if len(буфер) > 3:
                        del буфер[:-3]

                    break

                if начало > 0:
                    del буфер[:начало]

                if len(буфер) < 6:
                    break

                длина = буфер[3]
                размер = 6 + длина

                if len(буфер) < размер:
                    break

                команда = буфер[4]

                payload = bytes(
                    буфер[
                        5:5 + длина
                    ]
                )

                checksum = буфер[
                    5 + длина
                ]

                calc = длина ^ команда

                for b in payload:
                    calc ^= b

                if calc != checksum:

                    del буфер[0]
                    continue

                # Передаём только проверенный полный пакет без изменения.
                серый_пакет = bytes(буфер[:размер])
                if ser_out is not None:
                    ser_out.write(серый_пакет)
                    отправлено_пакетов += 1

                пакетов += 1

                # 182 = MSP_DISPLAYPORT
                if команда == 182:

                    обработать_displayport(
                        payload
                    )

                    # После штатного DRAW SCREEN добавляем нашу метку.
                    if ser_out is not None and payload and payload[0] == 4:
                        отправлено_наших_пакетов += отправить_нашу_метку(
                            ser_out
                        )

                del буфер[:размер]

            # ------------------------------------------------
            # HDMI
            # ------------------------------------------------

            рисовать(
                окно,
                поверхность_видео,
                позиция_видео
            )

            часы.tick(
                FPS
            )

    except KeyboardInterrupt:
        pass

    finally:

        камера.release()
        if ser is not None:
            ser.close()
        if ser_out is not None:
            ser_out.close()
        pygame.quit()


if __name__ == "__main__":
    main()
